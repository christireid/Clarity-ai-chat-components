/**
 * Get export statistics
 */
export function getExportStats(messages: ExportMessage[]): {
  totalMessages: number
  userMessages: number
  assistantMessages: number
  totalCharacters: number
  estimatedTokens: number
  sourcesCount: number
  hasTimestamps: boolean
} {
  const userMessages = messages.filter(m => m.role === 'user').length
  const assistantMessages = messages.filter(m => m.role === 'assistant').length
  const totalCharacters = messages.reduce((sum, m) => sum + m.content.length, 0)

  // Rough token estimation (1 token ≈ 4 characters)
  const estimatedTokens = Math.ceil(totalCharacters / 4)

  // Count total sources
  const sourcesCount = messages.reduce(
    (sum, m) => sum + (m.sources?.length || 0),
    0
  )

  // Check if messages have timestamps
  const hasTimestamps = messages.some(m => !!m.timestamp)

  return {
    totalMessages: messages.length,
    userMessages,
    assistantMessages,
    totalCharacters,
    estimatedTokens,
    sourcesCount,
    hasTimestamps,
  }
}
