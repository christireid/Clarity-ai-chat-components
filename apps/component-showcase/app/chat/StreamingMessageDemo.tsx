interface StreamMessage {
  id: string
  content: string
  isComplete: boolean
  timestamp: Date
  tokenCount: number
  thinkingSteps?: string[]
  error?: string
}

type StreamStatus = 'idle' | 'streaming' | 'paused' | 'completed' | 'error'
type ConnectionStatus = 'connected' | 'disconnected' | 'reconnecting'

